export function mbtiStyle(mbti: string): { name: string; desc: string } {
  const m = mbti.toUpperCase();
  if (m.includes("N") && m.includes("T"))
    return { name: "전술 설계자", desc: "구조와 논리로 싸우는 타입" };
  if (m.includes("N") && m.includes("F"))
    return { name: "무드 메이커", desc: "사람과 의미로 팀을 움직이는 타입" };
  if (m.includes("S") && m.includes("J"))
    return { name: "보급 관리자", desc: "체계와 꾸준함으로 전선을 지키는 타입" };
  return { name: "기습 스페셜리스트", desc: "현장 감각과 순발력으로 돌파하는 타입" };
}

